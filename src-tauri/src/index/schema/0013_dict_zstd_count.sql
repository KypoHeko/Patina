-- Запоминаем, сколько zstd-версий было на момент обучения словаря.
-- Раньше should_retrain использовал dict_id как proxy для этого значения,
-- но dict_id — автоинкремент строки в zstd_dicts и никак не связан с числом
-- zstd-версий: если словарь обучался с id=1 при 4 версиях, а потом добавили 8,
-- логика 12-1=11>=8 срабатывала случайно. Явная колонка делает решение точным.
ALTER TABLE zstd_dicts ADD COLUMN zstd_count_at_train INTEGER NOT NULL DEFAULT 0;
